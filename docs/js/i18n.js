let current = 'en';

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  }
  for (const el of document.querySelectorAll('[data-lang-block]')) el.hidden = el.dataset.langBlock !== current;
  return current;
}

export function getLang() {
  return current;
}

export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function num(n) {
  return new Intl.NumberFormat(current === 'fr' ? 'fr-FR' : 'en-US').format(Math.round(n));
}
