export const AUTO = 'auto';

const byCode = new Map(LANGUAGES.map(([code, en, native]) => [code.toLowerCase(), { code, en, native }]));

export function findLanguage(code) {
  if (!code) return null;
  const c = String(code).trim().toLowerCase();
  return byCode.get(c) || byCode.get(c.split(/[-_]/)[0]) || null;
}

// Name used inside prompts; English names are the least ambiguous for the model.
export function promptName(code) {
  return findLanguage(code)?.en ?? code;
}

const RTL = new Set(['ar', 'he', 'fa', 'ur', 'ps', 'sd', 'ug', 'yi', 'ckb']);
export function isRtl(code) {
  return RTL.has(String(code || '').split('-')[0].toLowerCase());
}
